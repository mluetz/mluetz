/**
 * Lokalisierte Restlaufzeit einer Meldefrist. Für Deutsch wird unverändert
 * lib/domain/incident-deadlines.ts#remainingLabel verwendet (zeichengenau);
 * Englisch: "due in …" / "overdue by …".
 */
export function formatRemaining(locale: Locale, dueAt: Date, now: Date): string {
  if (locale === "de") return remainingLabel(dueAt, now);
  const HOUR = 3_600_000;
  const ms = dueAt.getTime() - now.getTime();
  const abs = Math.abs(ms);
  const h = Math.floor(abs / HOUR);
  const m = Math.floor((abs % HOUR) / 60000);
  const core = h >= 48 ? `${Math.floor(h / 24)} d ${h % 24} h` : `${h} h ${m} min`;
  return ms >= 0 ? `due in ${core}` : `overdue by ${core}`;
}
